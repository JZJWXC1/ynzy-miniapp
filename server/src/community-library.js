// 归一化小区名：去空白、转小写，保证与前端 normalizeCommunityText 判定一致
function normalizeCommunityKey(value) {
  return String(value || '').trim().replace(/\s+/g, '').toLowerCase()
}

// 库内小区集合 = 拱墅小区名单 ∪ 已确认坐标的小区名
const KNOWN_COMMUNITY_KEYS = new Set(
  GONGSHU_COMMUNITIES.concat(Object.keys(communityCoordinates || {})).map(normalizeCommunityKey)
)

// 判断小区是否在服务端小区库中
function isKnownCommunity(value) {
  const key = normalizeCommunityKey(value)
  if (!key) return false
  return KNOWN_COMMUNITY_KEYS.has(key)
}

module.exports = {
  GONGSHU_COMMUNITIES,
  normalizeCommunityKey,
  isKnownCommunity
}
